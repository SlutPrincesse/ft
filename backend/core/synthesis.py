    def deduplicate_shards(self, shard_ids: List[str]) -> List[str]:
        seen = set()
        deduped = []
        for sid in shard_ids:
            record = self.filestore.get_shard(sid)
            if not record:
                continue
            source = record.get("source_code", "")
            key = hashlib.sha256(source.encode()).hexdigest() if source else sid
            if key not in seen:
                seen.add(key)
                deduped.append(sid)
        return deduped

    def topological_sort(self, shard_ids: List[str]) -> Tuple[List[str], List[str]]:
        graph: Dict[str, set] = {sid: set() for sid in shard_ids}
        for sid in shard_ids:
            record = self.filestore.get_shard(sid)
            if not record:
                continue
            for dep in record.get("import_dependencies", []):
                for other in shard_ids:
                    if other != sid:
                        other_rec = self.filestore.get_shard(other)
                        if other_rec and other_rec.get("name") in dep:
                            graph[sid].add(other)

        cycles = self._find_cycles(graph)
        if cycles:
            logger.warning(f"Circular dependency detected among shards: {cycles}")

        visited = set()
        result = []

        def visit(nid, stack):
            if nid in visited:
                return
            visited.add(nid)
            stack.add(nid)
            for dep in graph.get(nid, set()):
                if dep in stack:
                    logger.warning(f"Cycle detected: {nid} -> {dep}")
                    continue
                visit(dep, stack)
            stack.discard(nid)
            result.append(nid)

        for sid in shard_ids:
            visit(sid, set())
        return result, cycles

    def _find_cycles(self, graph: Dict[str, set]) -> List[str]:
        visited = set()
        rec_stack = set()
        cycles = []

        def dfs(node, path):
            visited.add(node)
            rec_stack.add(node)
            path.append(node)
            for neighbor in graph.get(node, set()):
                if neighbor not in visited:
                    dfs(neighbor, path)
                elif neighbor in rec_stack:
                    cycle_start = path.index(neighbor)
                    cycle = path[cycle_start:]
                    cycles.append(" -> ".join(cycle))
            path.pop()
            rec_stack.discard(node)

        for node in graph:
            if node not in visited:
                dfs(node, [])
        return cycles
