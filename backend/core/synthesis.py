        for category, items in shards.items():
            module_name = category
            file_path = f"{module_name}.py"
            imports = set()
            bodies = []
            for sid in items:
                record = self.filestore.get_shard(sid)
                if record:
                    for imp in record.get("import_dependencies", []):
                        imports.add(imp)
                    source_code = record.get("source_code", "")
