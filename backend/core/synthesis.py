    def _group_by_category(self, shard_ids: List[str]) -> Dict[str, List[str]]:
        groups: Dict[str, List[str]] = {}
        for sid in shard_ids:
            record = self.filestore.get_shard(sid)
            if record:
                cat = record.get("category", "utils")
                groups.setdefault(cat, []).append(sid)
        return groups

