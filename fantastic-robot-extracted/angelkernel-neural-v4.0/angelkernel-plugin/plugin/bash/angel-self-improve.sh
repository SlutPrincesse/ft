        shift
        mycelium_dig "$1"
        ;;
    --track|mycelium-track)
        mycelium_track
        ;;
    *)
        echo "AngelKernel Self-Improvement Engine v3 — with Mycelium Integration"
        echo ""
        echo "Usage:"
        echo "  angel-self-improve --learn <domain> <area> <content>"
        echo "  angel-self-improve --error <domain> <area> <content>"
        echo "  angel-self-improve --extract"
        echo "  angel-self-improve --evolve <context>"
        echo ""
        echo "Mycelium commands:"
        echo "  angel-self-improve --forage              — Cross-pollinate domains"
        echo "  angel-self-improve --connect <a> <b>     — Bridge two domains"
        echo "  angel-self-improve --dig [domain]        — Deep analysis of domain"
        echo "  angel-self-improve --track               — Show full tracker"
        ;;
esac
